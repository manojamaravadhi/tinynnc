#!/usr/bin/env python3
"""Generate a random TinyNNC MLP model, an input file, and the NumPy-computed
expected output.

The NumPy reference is written independently of the C code. It follows the
model's math, not TinyNNC's kernels, so agreement between the two is real
evidence that the parser, executor and passes are correct.

Example:
  python3 scripts/gen_mlp.py --dims 16,32,32,10 --batch 2 --softmax \
      --model examples/deep_mlp.txt --input deep_in.txt --expected deep_out.txt
"""
import argparse

import numpy as np

F32 = np.float32


def fmt(v):
    # '%.9g' prints enough digits for every float32 to survive the round trip exactly.
    return "%.9g" % float(v)


def write_matrix(lines, name, m):
    lines.append("CONST %s %d %d" % (name, m.shape[0], m.shape[1]))
    for row in m:
        lines.append("  " + " ".join(fmt(v) for v in row))


def sigmoid(x):
    return (F32(1) / (F32(1) + np.exp(-x))).astype(F32)


def softmax(x):
    e = np.exp(x - x.max(axis=1, keepdims=True))
    return (e / e.sum(axis=1, keepdims=True)).astype(F32)


def generate(dims, batch, acts, use_softmax, redundant, seed):
    """Returns (model_text, input array, expected output array)."""
    rng = np.random.default_rng(seed)
    x = rng.uniform(-1, 1, size=(batch, dims[0])).astype(F32)
    lines = ["# generated by scripts/gen_mlp.py seed=%d dims=%s batch=%d redundant=%s"
             % (seed, ",".join(map(str, dims)), batch, redundant),
             "INPUT x %d %d" % (batch, dims[0])]
    h = x
    cur = "x"
    for i in range(len(dims) - 1):
        k, n = dims[i], dims[i + 1]
        # Scale weights by 1/sqrt(k) so activations stay around 1 in every layer,
        # just as with a properly initialized network.
        W = (rng.standard_normal((k, n)) / np.sqrt(k)).astype(F32)
        b = rng.uniform(-0.1, 0.1, size=(1, n)).astype(F32)
        write_matrix(lines, "W%d" % i, W)
        if redundant:
            # The bias is written as the sum of two constants: a job for constant folding.
            ba = rng.uniform(-0.1, 0.1, size=(1, n)).astype(F32)
            bb = (b - ba).astype(F32)
            b = (ba + bb).astype(F32)  # exactly what the C ADD computes
            write_matrix(lines, "Ba%d" % i, ba)
            write_matrix(lines, "Bb%d" % i, bb)
            lines.append("ADD B%d Ba%d Bb%d" % (i, i, i))
        else:
            write_matrix(lines, "B%d" % i, b)
        lines.append("MATMUL m%d %s W%d" % (i, cur, i))
        if redundant:
            lines.append("MATMUL dup%d %s W%d" % (i, cur, i))   # CSE
            lines.append("SIGMOID dbg%d dup%d" % (i, i))         # dead branch
        lines.append("ADD a%d m%d B%d" % (i, i, i))
        h = (h @ W).astype(F32)
        h = (h + b).astype(F32)
        cur = "a%d" % i
        act = acts[i] if i < len(acts) else "none"
        if act == "relu":
            lines.append("RELU r%d %s" % (i, cur))
            cur = "r%d" % i
            if redundant:
                lines.append("RELU rr%d %s" % (i, cur))          # RELU(RELU)
                cur = "rr%d" % i
            h = np.maximum(h, F32(0))
        elif act == "sigmoid":
            lines.append("SIGMOID s%d %s" % (i, cur))
            cur = "s%d" % i
            h = sigmoid(h)
        if redundant and i == 0:
            write_matrix(lines, "I%d" % i, np.eye(n, dtype=F32))
            lines.append("MATMUL id%d %s I%d" % (i, cur, i))     # identity
            cur = "id%d" % i
            write_matrix(lines, "Z%d" % i, np.zeros((1, n), dtype=F32))
            lines.append("ADD z%d %s Z%d" % (i, cur, i))          # + 0
            cur = "z%d" % i
    if use_softmax:
        lines.append("SOFTMAX y %s" % cur)
        cur = "y"
        h = softmax(h)
    lines.append("OUTPUT %s" % cur)
    return "\n".join(lines) + "\n", x, h.astype(F32)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dims", default="16,32,10", help="layer widths, e.g. 64,128,64")
    ap.add_argument("--batch", type=int, default=1)
    ap.add_argument("--acts", default="relu",
                    help="activation per hidden layer (relu|sigmoid|none), comma list; "
                         "the last listed one repeats; the final layer has none")
    ap.add_argument("--softmax", action="store_true")
    ap.add_argument("--redundant", action="store_true",
                    help="insert redundant ops for the optimizer to remove")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--model", required=True)
    ap.add_argument("--input")
    ap.add_argument("--expected")
    a = ap.parse_args()
    dims = [int(d) for d in a.dims.split(",")]
    act_list = a.acts.split(",")
    acts = [act_list[min(i, len(act_list) - 1)] for i in range(len(dims) - 2)] + ["none"]
    text, x, y = generate(dims, a.batch, acts, a.softmax, a.redundant, a.seed)
    with open(a.model, "w") as f:
        f.write(text)
    if a.input:
        np.savetxt(a.input, x.reshape(1, -1), fmt="%.9g")
    if a.expected:
        np.savetxt(a.expected, y.reshape(1, -1), fmt="%.9g")


if __name__ == "__main__":
    main()
